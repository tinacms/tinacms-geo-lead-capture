// Every copy button shares this: try the clipboard, and if it is unavailable
// fall back to selecting the text in the hidden <pre> so Cmd/Ctrl+C works.
const copyOut = async (btn, text) => {
  const pre = $('#md-pre');
  const label = btn.dataset.label;
  try {
    await navigator.clipboard.writeText(text);
    btn.textContent = 'Copied ✓';
  } catch {
    btn.textContent = 'Press Cmd/Ctrl+C';
    if (pre) {
      pre.textContent = text;
      const range = document.createRange();
      range.selectNodeContents(pre);
      const sel = window.getSelection();
      sel.removeAllRanges();
      sel.addRange(range);
    }
  }
  setTimeout(() => {
    btn.innerHTML = `${COPY_ICON}${label}`;
  }, 2200);
};

// Registered once, and reads lastReport rather than closing over a report, so
// analyzing a second URL cannot leave a stale handler behind.
results.addEventListener('click', (e) => {
  const btn = e.target.closest('#copy-md, #copy-prompt-all, [data-prompt-check]');
  if (!btn || !lastReport) {
    return;
  }
  if (btn.id === 'copy-md') {
    copyOut(btn, buildMarkdown(lastReport));
    return;
  }
  const failing = lastReport.categories
    .flatMap((c) => c.checks)
    .filter((c) => c.status === 'warn' || c.status === 'fail');
  const checks =
    btn.id === 'copy-prompt-all'
      ? failing
      : failing.filter((c) => c.id === btn.dataset.promptCheck);
  if (checks.length) {
    copyOut(btn, buildPrompt(lastReport, checks));
  }
});

const renderResults = (report) => {
  lastReport = report;
  setEditorialLoaded(report);
  document
    .getElementById('editorial')
    .insertAdjacentHTML(
      'afterend',
      `<div class="post-tease" id="post-tease">${blockerBanner(report)}${topFixes(report)}<div id="gate-slot">${autoFull ? fullReport(report) : leadGate(report)}</div></div>`,
    );
  revealAll();
  armScrollHint();
  if (autoFull) {
    // Arrived via the email deep-link — skip the gate, show the full report.
    wireAccordion();
  } else {
    wireLeadForm(report);
  }
};

const wireLeadForm = (report) => {
  const form = $('#lead-form');
  if (!form) {
    return;
  }
  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    const email = $('#lead-email').value.trim();
    const phone = $('#lead-phone').value.trim();
    const errEl = $('#lead-error');
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      errEl.textContent = 'Enter a valid email address.';
      errEl.classList.remove('hidden');
      return;
    }
    if ((phone.match(/\d/g) || []).length < 6) {
      errEl.textContent = 'Enter a valid phone number.';
      errEl.classList.remove('hidden');
      return;
    }
    errEl.classList.add('hidden');
    const btn = $('#lead-btn');
    btn.disabled = true;
    btn.textContent = 'Sending…';
    try {
      await fetch('/geo/api/lead', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          email,
          phone,
          website: report.finalUrl,
          note: `AI Search Readiness: ${report.finalUrl} scored ${report.overall}/100 (${report.grade}).`,
          report: {
            url: report.finalUrl,
            overall: report.overall,
            grade: report.grade,
            passCount: report.passCount,
            totalScored: report.totalScored,
            categories: report.categories.map((c) => ({ title: c.title, score: c.score })),
            topFixes: report.topFixes.map((f) => ({ label: f.label, why: f.why })),
          },
        }),
      });
    } catch {
      // Never hold the report hostage to the CRM.
    }
    $('#gate-slot').innerHTML = fullReport(report);
    wireAccordion();
    revealAll();
  });
};

$('#analyze-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  const url = $('#url').value.trim();
  const errEl = $('#form-error');
  const btn = $('#analyze-btn');
  if (!url) {
    errEl.textContent = 'Enter a URL to analyze.';
    errEl.classList.remove('hidden');
    return;
  }
  errEl.classList.add('hidden');
  results.innerHTML = editorialShell();
  results.classList.remove('hidden');
  startEditorial();
  btn.disabled = true;
  const minLoad = new Promise((r) => setTimeout(r, 2000));
  const fail = (msg) => {
    results.innerHTML = '';
    results.classList.add('hidden');
    errEl.textContent = msg;
    errEl.classList.remove('hidden');
  };
  try {
    const res = await fetch('/geo/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ url }),
    });
    const data = await res.json();
    if (!res.ok) {
      fail(data.error || 'Something went wrong. Try another URL.');
      return;
    }
    await minLoad;
    renderResults(data);
    requestAnimationFrame(() =>
      results.scrollIntoView({ behavior: 'smooth', block: 'start' }),
    );
  } catch {
    fail('Network error. Please try again.');
  } finally {
    btn.disabled = false;
  }
});

