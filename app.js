const STATUS_WORD = { pass: 'PASS', warn: 'WARN', fail: 'FAIL', info: 'INFO' };

const buildMarkdown = (report) => {
  const out = [
    `# AI Search Readiness — ${report.finalUrl}`,
    '',
    `**Score: ${report.overall}/100 (Grade ${report.grade})** — ${report.passCount}/${report.totalScored} checks passed.`,
    '_Generated by the TinaCMS AI Search Readiness checker (tina.io). Fixes and sources included below._',
    '',
  ];
  for (const cat of report.categories) {
    out.push(`## ${cat.title} — ${cat.score}/100`, '');
    for (const ch of cat.checks) {
      out.push(`- **[${STATUS_WORD[ch.status]}] ${ch.label}** — ${ch.detail}`);
      if (ch.status !== 'pass') {
        out.push(`  - Fix: ${ch.fix}`);
      }
      out.push(`  - Why: ${ch.why}`);
      out.push(`  - Source (${ch.evidence.type}): ${ch.evidence.source} — ${ch.evidence.url}`);
    }
    out.push('');
  }
  return out.join('\n');
};

