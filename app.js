const results = $('#results');

// Scroll-triggered fade-ins. Elements with .reveal start hidden (only when JS is
// present, via .reveal-enabled) and animate in as they enter the viewport.
document.documentElement.classList.add('reveal-enabled');
const revealIO = new IntersectionObserver(
  (entries) => {
    for (const e of entries) {
      if (e.isIntersecting) {
        e.target.classList.add('reveal-in');
        revealIO.unobserve(e.target);
      }
    }
  },
  { rootMargin: '0px 0px -8% 0px', threshold: 0.08 },
);
const revealAll = () => {
  for (const el of document.querySelectorAll('.reveal:not(.reveal-in)')) {
    revealIO.observe(el);
  }
};

// "Scroll for more" hint: shows if the user lingers near the top after a result
// loads, and dissipates the moment they scroll.
const scrollHint = $('#scroll-hint');
let hintTimer;
const armScrollHint = () => {
  clearTimeout(hintTimer);
  scrollHint?.classList.remove('show');
  hintTimer = setTimeout(() => {
    if (window.scrollY < 140 && document.body.scrollHeight > window.innerHeight + 240) {
      scrollHint?.classList.add('show');
    }
  }, 2600);
};
window.addEventListener(
  'scroll',
  () => {
    clearTimeout(hintTimer);
    scrollHint?.classList.remove('show');
  },
  { passive: true },
);

let geminiHandle = null;

const startGemini = () => {
  const g = $('#gemini');
  if (!g) {
    return;
  }
  const metalEl = g.querySelector('.gemini-metal');
  metalEl.style.maskImage = GEMINI_MASK;
  metalEl.style.webkitMaskImage = GEMINI_MASK;
  geminiHandle?.destroy();
  // Fast pulsing metal while loading.
  geminiHandle = metal(g.querySelector('canvas'), { speed: 0.9, pulse: 0.7 });
  requestAnimationFrame(() => g.classList.add('in'));
};

const setGeminiLoaded = (report) => {
  const g = $('#gemini');
  $('#gemini-score').textContent = report.overall;
  $('#gemini-stats').innerHTML = geminiStats(report);
  // Slow the metal and settle.
  geminiHandle?.setSpeed(0.16);
  geminiHandle?.setPulse(0);
  requestAnimationFrame(() =>
    requestAnimationFrame(() => g.classList.add('loaded')),
  );
};

const wireAccordion = () => {
  results.querySelectorAll('.check-btn').forEach((btn) => {
    btn.addEventListener('click', () => btn.closest('.check').classList.toggle('open'));
  });
};

const wireCopy = (report) => {
  const btn = $('#copy-md');
  const pre = $('#md-pre');
  if (!btn || !pre) {
    return;
  }
  const md = buildMarkdown(report);
  pre.textContent = md;
  btn.addEventListener('click', async () => {
    try {
      await navigator.clipboard.writeText(md);
      btn.textContent = 'Copied ✓';
    } catch {
      btn.textContent = 'Press Cmd/Ctrl+C';
      const range = document.createRange();
      range.selectNodeContents(pre);
      const sel = window.getSelection();
      sel.removeAllRanges();
      sel.addRange(range);
    }
    setTimeout(() => {
      btn.textContent = 'Copy report as Markdown';
    }, 2200);
  });
};

const renderResults = (report) => {
  setGeminiLoaded(report);
  $('#gemini').insertAdjacentHTML(
    'afterend',
    `<div class="post-tease" id="post-tease">${topFixes(report)}<div id="gate-slot">${leadGate(report)}</div></div>`,
  );
  revealAll();
  armScrollHint();
  wireLeadForm(report);
};

const wireLeadForm = (report) => {
  const form = $('#lead-form');
  if (!form) {
    return;
  }
  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    const email = $('#lead-email').value.trim();
    const errEl = $('#lead-error');
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      errEl.textContent = 'Enter a valid email address.';
      errEl.classList.remove('hidden');
      return;
    }
    errEl.classList.add('hidden');
    const btn = $('#lead-btn');
    btn.disabled = true;
    btn.textContent = 'Unlocking…';
    try {
      await fetch('/api/lead', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          email,
          note: `AI Search Readiness: ${report.finalUrl} scored ${report.overall}/100 (${report.grade}).`,
        }),
      });
    } catch {
      // Never hold the report hostage to the CRM.
    }
    $('#gate-slot').innerHTML = fullReport(report);
    wireAccordion();
    wireCopy(report);
    const am = document.querySelector('.agent-metal');
    if (am) {
      metal(am, { speed: 0.18, feature: 760 });
    }
    revealAll();
  });
};

$('#analyze-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  const url = $('#url').value.trim();
  const errEl = $('#form-error');
  const btn = $('#analyze-btn');
  if (!url) {
    errEl.textContent = 'Enter a URL to analyze.';
    errEl.classList.remove('hidden');
    return;
  }
  errEl.classList.add('hidden');
  results.innerHTML = geminiShell();
  results.classList.remove('hidden');
  startGemini();
  btn.disabled = true;
  const minLoad = new Promise((r) => setTimeout(r, 1200));
  const fail = (msg) => {
    geminiHandle?.destroy();
    geminiHandle = null;
    results.innerHTML = '';
    results.classList.add('hidden');
    errEl.textContent = msg;
    errEl.classList.remove('hidden');
  };
  try {
    const res = await fetch('/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ url }),
    });
    const data = await res.json();
    if (!res.ok) {
      fail(data.error || 'Something went wrong. Try another URL.');
      return;
    }
    await minLoad;
    renderResults(data);
  } catch {
    fail('Network error. Please try again.');
  } finally {
    btn.disabled = false;
  }
});

