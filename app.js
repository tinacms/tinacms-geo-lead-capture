const countUp = (el, to, ms, colorize) => {
  const start = performance.now();
  const tick = (now) => {
    const t = Math.min(1, (now - start) / ms);
    const v = Math.round(to * (1 - (1 - t) ** 3));
    el.textContent = v;
    if (colorize) {
      el.style.color = scoreColor(v);
    }
    if (t < 1) {
      requestAnimationFrame(tick);
    }
  };
  requestAnimationFrame(tick);
};

