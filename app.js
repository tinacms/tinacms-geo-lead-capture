// Scroll-triggered fade-ins. Elements with .reveal start hidden (only when JS is
// present, via .reveal-enabled) and animate in as they enter the viewport.
document.documentElement.classList.add('reveal-enabled');
const revealIO = new IntersectionObserver(
  (entries) => {
    for (const e of entries) {
      if (e.isIntersecting) {
        e.target.classList.add('reveal-in');
        revealIO.unobserve(e.target);
      }
    }
  },
  { rootMargin: '0px 0px -8% 0px', threshold: 0.08 },
);
const revealAll = () => {
  for (const el of document.querySelectorAll('.reveal:not(.reveal-in)')) {
    revealIO.observe(el);
  }
};

// "Scroll for more" hint: shows if the user lingers near the top after a result
// loads, and dissipates the moment they scroll.
const scrollHint = $('#scroll-hint');
let hintTimer;
const armScrollHint = () => {
  clearTimeout(hintTimer);
  scrollHint?.classList.remove('show');
  hintTimer = setTimeout(() => {
    if (window.scrollY < 140 && document.body.scrollHeight > window.innerHeight + 240) {
      scrollHint?.classList.add('show');
    }
  }, 2600);
};
window.addEventListener(
  'scroll',
  () => {
    clearTimeout(hintTimer);
    scrollHint?.classList.remove('show');
  },
  { passive: true },
);

